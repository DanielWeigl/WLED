/*
  Output smoothing — global spatial + temporal filter over the composed frame buffer.
  See docs/design/output-smoothing.md
*/
#ifndef WLED_OUTPUT_SMOOTHING_H
#define WLED_OUTPUT_SMOOTHING_H

#if defined(WLED_DISABLE_GLOBAL_PIXELBUFFER) && !defined(WLED_DISABLE_OUTPUT_SMOOTHING)
  #define WLED_DISABLE_OUTPUT_SMOOTHING
#endif

#ifndef WLED_DISABLE_OUTPUT_SMOOTHING

#include <stdint.h>
#include <stddef.h>

// Spatial: sm.x unit is 0.1 LED (sigma), 0..50 → 0..5 LEDs.
// Temporal: sm.t unit is 10 ms (tau), 0..100 → 0..1000 ms.
constexpr uint8_t SMOOTH_SPATIAL_MAX  = 50;
constexpr uint8_t SMOOTH_TEMPORAL_MAX = 100;
constexpr unsigned SMOOTH_TEMPORAL_STAGES = 2;
// Binomial [1 2 1]/4 for small sigma only (spatial <= this → cheap 0..2 full passes).
// Above: forward+backward IIR keeps cost fixed at 2 passes per axis for any sigma.
constexpr uint8_t SMOOTH_SPATIAL_BINOMIAL_MAX = 10;

// AI: below section was generated by an AI
// Global output smoother: spatial blur + cascaded 1-pole temporal IIR on _pixels[].
// setTargets() is cheap and may be called from any task; allocation/free happens in apply().
class OutputSmoother {
  public:
    OutputSmoother() = default;
    ~OutputSmoother() { freeHistory(); }

    // Store desired strengths (any task). apply() reacts on the next frame.
    void setTargets(uint8_t spatial, uint8_t temporal);
    inline uint8_t getSpatial()  const { return _spatial; }
    inline uint8_t getTemporal() const { return _temporal; }
    inline bool isActive() const { return _spatial > 0 || _temporal > 0; }
    inline size_t memoryUsed() const { return _histLen * SMOOTH_TEMPORAL_STAGES * 2 * sizeof(uint32_t); }

    // Force history re-sync from the next apply() input (no fade-in of stale content).
    void reset();

    // Called from WS2812FX::show() only (main-loop context).
    // width/height: matrix dims (height==1 for 1D). len: total logical pixels in _pixels[].
    // processW: false skips the white channel in the temporal IIR (RGB-only strips).
    // When both strengths are 0, px may be nullptr — apply() only frees history.
    void apply(uint32_t *px, unsigned width, unsigned height, unsigned len, unsigned dtMs, bool processW = true);

  private:
    void ensureHistory(unsigned len);
    void freeHistory();
    void seedHistory(const uint32_t *px, unsigned len);
    void blurSpatial(uint32_t *px, unsigned width, unsigned height, unsigned len) const;
    void blur1D(uint32_t *px, unsigned len, unsigned stride, uint8_t weight) const;
    void blur1DVertical(uint32_t *px, unsigned width, unsigned height, uint8_t weight) const;
    void iirSpatial1D(uint32_t *px, unsigned len, unsigned stride, uint16_t alphaQ15) const;
    void blurTemporal(uint32_t *px, unsigned len, unsigned dtMs, bool processW);

    volatile uint8_t _spatial  = 0;   // 0..SMOOTH_SPATIAL_MAX
    volatile uint8_t _temporal = 0;   // 0..SMOOTH_TEMPORAL_MAX
    volatile bool _needsReset = true; // written from network task via setTargets()/reset()
    bool     _allocFailed = false;
    unsigned _histLen = 0;
    // Per pixel, per stage: two uint32_t packing R|G<<16 and B|W<<16 as 8.8 fixed-point.
    // Always accessed as 32-bit words (safe for BFRALLOC_NOBYTEACCESS / classic ESP32 IRAM).
    uint32_t *_hist = nullptr;
};
// AI: end

#endif // WLED_DISABLE_OUTPUT_SMOOTHING
#endif // WLED_OUTPUT_SMOOTHING_H
